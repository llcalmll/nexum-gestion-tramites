/** +1 nombre de pila, -1 apellido, 0 no se sabe (un apellido compuesto, "DE AYA", se mira por su última palabra). */
const tipo = (palabra: string) => {
  const w = clave(palabra).split(" ").pop() ?? "";
  return NOMBRES_PILA.has(w) ? 1 : APELLIDOS.has(w) ? -1 : 0;
};

/**
 * El orden de un nombre ya partido en palabras (los apellidos compuestos juntos): "apellidos" si arranca con los
 * apellidos, "nombres" si arranca con los nombres, null si no hay cómo saber. Se cuentan las señales de cada forma
 * (apellidos primero: las dos primeras son apellidos y lo demás nombres de pila; nombres primero: al revés) y se
 * pide al menos dos para decidir: un solo nombre que no está en la lista (FIDEL ANDRES) no voltea nada.
 */
export function ordenDelNombre(palabras: string[]): "nombres" | "apellidos" | null {
  const n = palabras.length;
  // Con paréntesis, números o notas ("MIGUEL ARANGO (ASESORÍAS ...)") no es un nombre limpio: no se adivina.
  if (n < 2 || palabras.some((w) => /[^\p{L}\s'-]/u.test(w))) return null;
  const t = palabras.map(tipo);
  const es = (i: number, v: 1 | -1) => (t[i] === v ? 1 : 0);
  // Apellidos primero: 1.ª (y 2.ª, con tres o más) apellidos; el resto, nombres de pila.
  const corte = n === 2 ? 1 : 2;
  let apellidos = 0, nombres = 0;
  for (let i = 0; i < n; i++) apellidos += i < corte ? es(i, -1) : es(i, 1);
  // Nombres primero: las últimas (una con dos palabras, dos con más) apellidos; lo de antes, nombres de pila.
  for (let i = 0; i < n; i++) nombres += i >= n - corte ? es(i, -1) : es(i, 1);
  if (apellidos >= 2 && apellidos > nombres) return "apellidos";
  if (nombres >= 2 && nombres > apellidos) return "nombres";
  return null;
}
